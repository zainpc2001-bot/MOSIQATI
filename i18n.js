function t(key) {
  var lang = localStorage.getItem("mosiqati_lang") || "ar";
  return translations[lang] && translations[lang][key]
    ? translations[lang][key]
    : translations["ar"][key] || key;
}

function getCurrentLang() {
  return localStorage.getItem("mosiqati_lang") || "ar";
}

function getCurrentTheme() {
  return localStorage.getItem("mosiqati_theme") || "light";
}

function applyTheme(theme) {
  if (theme === "dark") {
    document.documentElement.setAttribute("data-theme", "dark");
  } else {
    document.documentElement.removeAttribute("data-theme");
  }
  localStorage.setItem("mosiqati_theme", theme);
}

function applyLang(lang) {
  localStorage.setItem("mosiqati_lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

// Apply settings immediately on load (before DOM ready to avoid flicker)
(function () {
  var theme = localStorage.getItem("mosiqati_theme") || "light";
  var lang = localStorage.getItem("mosiqati_lang") || "ar";
  applyTheme(theme);
  applyLang(lang);
})();
